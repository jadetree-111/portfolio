"""Dev-time generator for shared/solar-terms-data.js (not needed at runtime).

Usage:
  python -I gen-solar-terms.py <dir containing lunar_python> <out.js> [first_year] [last_year]

lunar_python is installed with `pip install --target <empty dir> lunar_python==1.4.8`
and only imported from that directory.
"""
import datetime
import sys

lib, out = sys.argv[1], sys.argv[2]
first = int(sys.argv[3]) if len(sys.argv) > 3 else 2020
last = int(sys.argv[4]) if len(sys.argv) > 4 else 2060
sys.path.insert(0, lib)
from lunar_python import Solar  # noqa: E402

NAMES = ['小寒', '大寒', '立春', '雨水', '惊蛰', '春分', '清明', '谷雨', '立夏', '小满', '芒种', '夏至',
         '小暑', '大暑', '立秋', '处暑', '白露', '秋分', '寒露', '霜降', '立冬', '小雪', '大雪', '冬至']

lines = []
for year in range(first, last + 1):
    found = {}
    day = datetime.date(year, 1, 1)
    while day.year == year:
        name = Solar.fromYmd(year, day.month, day.day).getLunar().getJieQi()
        if name:
            found[name] = day
        day += datetime.timedelta(days=1)
    assert sorted(found) == sorted(NAMES), f'{year}: unexpected terms {sorted(found)}'
    for i, name in enumerate(NAMES):
        assert found[name].month == i // 2 + 1, f'{year} {name} in month {found[name].month}'
    lines.append(f"  {year}: '{''.join(f'{found[n].day:02d}' for n in NAMES)}',")

header = (
    '// Generated by scripts/dev/gen-solar-terms.py (lunar_python 1.4.8). Do not edit by hand.\n'
    '// Each value holds 24 two-digit days of month, ordered 小寒..冬至; term i falls in month floor(i/2)+1.\n'
)
with open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(header + 'export const TERM_DAYS = {\n' + '\n'.join(lines) + '\n};\n')
print(f'wrote {len(lines)} years to {out}')
